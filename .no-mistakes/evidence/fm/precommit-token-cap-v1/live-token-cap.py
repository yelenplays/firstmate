"""Drive the installed production hook with real git commits in disposable repos."""
import json, os, pathlib, shutil, subprocess, sys

root = pathlib.Path.cwd()
evidence = pathlib.Path(sys.argv[1])
fixtures = root / '.test-token-cap-tmp' / 'live'
fixtures.mkdir(parents=True, exist_ok=True)
env = dict(os.environ)
for key in list(env):
    if key.startswith('GIT_'):
        env.pop(key)
env.update(GIT_CONFIG_GLOBAL='/dev/null', GIT_CONFIG_NOSYSTEM='1',
           GIT_AUTHOR_NAME='Hook Live Validation', GIT_AUTHOR_EMAIL='test@example.invalid',
           GIT_COMMITTER_NAME='Hook Live Validation', GIT_COMMITTER_EMAIL='test@example.invalid')
log = (evidence / 'live-commits.log').open('w')
results = []

def git(repo, *args):
    p = subprocess.run(['git', '-C', str(repo), *args], env=env, text=True, capture_output=True)
    log.write(f'$ git -C {repo.name} ' + ' '.join(repr(a) for a in args) + '\n')
    log.write(f'exit={p.returncode}\n' + p.stdout + p.stderr + '\n')
    log.flush()
    return p

def ok(p):
    assert p.returncode == 0, p.stderr
    return p.stdout.strip()

def repo(name):
    d = fixtures / name
    d.mkdir()
    ok(git(d, 'init', '-q'))
    (d / 'bin').mkdir()
    (d / '.githooks').mkdir()
    shutil.copy2(root / 'bin/fm-precommit-token-cap.sh', d / 'bin/fm-precommit-token-cap.sh')
    shutil.copy2(root / '.githooks/pre-commit', d / '.githooks/pre-commit')
    ok(git(d, 'config', 'core.hooksPath', '.githooks'))
    return d

def put(d, name, size, header=b'', fill=b'x'):
    p = d / name
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(header + fill * (size-len(header)))
    log.write(f'write {d.name}/{name!r}: {size} bytes, header={header!r}\n')

def add(d, *paths):
    ok(git(d, 'add', '--', *paths))

def commit(d, message, allowed=True, names=(), seed=False):
    before = git(d, 'rev-parse', '--verify', 'HEAD').stdout.strip()
    p = git(d, 'commit', *(('--no-verify',) if seed else ()), '-m', message)
    after = git(d, 'rev-parse', '--verify', 'HEAD').stdout.strip()
    if not allowed and p.returncode == 0:
        ok(git(d, 'ls-tree', '-rl', 'HEAD'))
        for name in names:
            ok(git(d, 'check-attr', '--cached', 'linguist-generated', 'linguist-vendored', '--', name))
    if allowed:
        ok(p)
        assert after != before, 'commit did not advance HEAD'
        ok(git(d, 'ls-tree', '-rl', 'HEAD'))
    else:
        assert p.returncode != 0, f'oversized commit accepted: {message}'
        assert before == after, 'refused commit advanced HEAD'
        assert 'precommit-token-cap:' in p.stderr, 'not a token-cap refusal'
        assert all(name in p.stderr for name in names), 'missing failing path'
        assert 'How to split:' in p.stderr and 'linked pages' in p.stderr
    return p

def run(name, fn):
    log.write('\n=== ' + name + ' ===\n')
    try:
        fn()
        result, reason = 'pass', ''
    except Exception as exc:
        result, reason = 'fail', str(exc)
        log.write('ASSERTION FAILED: ' + reason + '\n')
    results.append(dict(name=name, result=result, live=True, evidence=str(evidence / 'live-commits.log'), reason=reason))

def boundary():
    d=repo('boundary')
    put(d, 'exact.txt', 20000); add(d, 'exact.txt'); commit(d, 'exactly 5000 tokens allowed')
    put(d, 'new.txt', 20001); add(d, 'new.txt')
    p=commit(d, 'one byte above cap refused', False, ['new.txt'])
    assert '20001 bytes = 5001 tokens' in p.stderr

def ratchet():
    d=repo('ratchet')
    put(d, 'old.txt', 24000); add(d, 'old.txt'); commit(d, 'seed legacy file', seed=True)
    put(d, 'old.txt', 24000, fill=b'y'); add(d, 'old.txt'); commit(d, 'same size edit allowed')
    put(d, 'old.txt', 23000); add(d, 'old.txt'); commit(d, 'shrink allowed')
    put(d, 'old.txt', 23001); add(d, 'old.txt'); commit(d, 'one byte growth refused', False, ['old.txt'])
    ok(git(d, 'reset', '-q', 'HEAD', '--', 'old.txt'))
    put(d, 'small.txt', 5); add(d, 'small.txt'); commit(d, 'unstaged legacy growth ignored')
    put(d, 'small.txt', 20001); add(d, 'small.txt'); commit(d, 'crossing limit refused', False, ['small.txt'])

def staged():
    d=repo('staged')
    put(d, 'staged.txt', 21000); add(d, 'staged.txt'); put(d, 'staged.txt', 1)
    commit(d, 'oversized staged blob refused despite tiny disk file', False, ['staged.txt'])
    add(d, 'staged.txt'); put(d, 'staged.txt', 21000); put(d, 'untracked.txt', 30000)
    commit(d, 'tiny staged blob commits despite oversized disk and untracked files')
    assert ok(git(d, 'cat-file', '-s', 'HEAD:staged.txt')) == '1'

def exclusions():
    d=repo('exclusions')
    put(d, 'package-lock.json', 30000)
    put(d, 'generated.go', 30000, b'// Code generated by generator. DO NOT EDIT.\n')
    put(d, 'generated.js', 30000, b'/* @generated */\n')
    put(d, 'image.bin', 30000, fill=b'\0')
    put(d, 'vendor.js', 30000)
    (d/'.gitattributes').write_text('vendor.js linguist-vendored\n')
    add(d, 'package-lock.json', 'generated.go', 'generated.js', 'image.bin', 'vendor.js', '.gitattributes')
    (d/'.gitattributes').write_text('')
    commit(d, 'lockfile binary codegen and staged vendor attributes allowed')
    put(d, 'authored.py', 21000); add(d, 'authored.py')
    commit(d, 'unmarked source still refused in same repo', False, ['authored.py'])

def incidental():
    for i, text in enumerate(['DO NOT EDIT', 'do not edit']):
        d=repo('incidental'+str(i))
        put(d, 'handwritten.py', 21000, f'# When updating this file, {text} the table below.\n'.encode())
        add(d, 'handwritten.py')
        commit(d, 'incidental prose is not codegen', False, ['handwritten.py'])

def attributes():
    for state in ['untracked', 'modified']:
        d=repo('attrs-'+state)
        if state == 'modified':
            (d/'.gitattributes').write_text(''); add(d, '.gitattributes'); commit(d, 'seed attributes')
        put(d, 'handwritten.py', 21000); add(d, 'handwritten.py')
        (d/'.gitattributes').write_text('handwritten.py linguist-generated\n')
        commit(d, 'unstaged attribute cannot exempt source', False, ['handwritten.py'])
        add(d, '.gitattributes'); (d/'.gitattributes').write_text('')
        commit(d, 'staged attribute can exempt source despite worktree edit')

def rename_delete():
    d=repo('rename-delete')
    put(d, 'legacy.txt', 24000); add(d, 'legacy.txt'); commit(d, 'seed legacy', seed=True)
    ok(git(d, 'mv', 'legacy.txt', 'renamed.txt')); commit(d, 'pure rename allowed')
    ok(git(d, 'mv', 'renamed.txt', 'renamed-again.txt'))
    put(d, 'renamed-again.txt', 24001); add(d, 'renamed-again.txt')
    commit(d, 'rename and growth in same commit refused', False, ['renamed-again.txt'])
    ok(git(d, 'reset', '--hard', 'HEAD'))
    ok(git(d, 'rm', 'renamed.txt')); commit(d, 'legacy deletion allowed')

def multi_paths():
    d=repo('unusual-paths')
    names=['docs/two words.md', 'line\nbreak.txt']
    for name in names: put(d,name,21000)
    add(d,*names)
    p=commit(d,'all unusual paths listed',False,names)
    assert '2 staged file(s)' in p.stderr

def attribute_value_filename():
    d=repo('attribute-value-filename')
    put(d, 'set', 21000); add(d, 'set')
    commit(d, 'authored file named set must not be exempt', False, ['set'])

try:
    for name, fn in [('Exact byte boundary and actionable splitting instructions',boundary),
                     ('Legacy oversized files ratchet and crossing limit',ratchet),
                     ('Only staged blobs count',staged),
                     ('Lockfile binary codegen and staged attribute exemptions',exclusions),
                     ('Incidental do-not-edit prose is not generated',incidental),
                     ('Unstaged attributes cannot bypass staged-only enforcement',attributes),
                     ('Oversized rename growth and deletion',rename_delete),
                     ('One refusal lists all oversized unusual paths',multi_paths),
                     ('Authored filename matching attribute value is not exempt',attribute_value_filename)]:
        run(name,fn)
finally:
    shutil.rmtree(fixtures)
    log.close()
    (evidence/'live-results.json').write_text(json.dumps(results,indent=2)+'\n')
print(json.dumps(results,indent=2))
sys.exit(any(r['result']=='fail' for r in results))
